package model

// AgentResponseMeta contains unified metadata for all three Agent responses.
// This is the single source of truth for frontend to determine
// LLM / repair / fallback / mock status.
//
// All fields are required (no omitempty) so the frontend can stably consume
// them without checking for existence.
type AgentResponseMeta struct {
	AgentName      string `json:"agent_name"`
	GeneratedBy    string `json:"generated_by"`
	AgentStatus    string `json:"agent_status"`
	FallbackReason string `json:"fallback_reason"`
	ErrorCode      string `json:"error_code"`
	RepairApplied  bool   `json:"repair_applied"`
	SchemaValid    bool   `json:"schema_valid"`
	RequestID      string `json:"request_id"`
}

// Agent name constants.
const (
	AgentNameMatchAnalysis      = "match_analysis"
	AgentNameRecommendation     = "recommendation"
	AgentNameResumeOptimization = "resume_optimization"
)

// Generated by constants.
const (
	GeneratedByLLMAgent            = "llm_agent"
	GeneratedByMockAgent           = "mock_agent"
	GeneratedByDeepFallbackAgent   = "deep_fallback_agent"
	GeneratedByMockQuality         = "mock_quality" // legacy; prefer GeneratedByDeepFallbackAgent
)

// Agent status constants.
const (
	AgentStatusSuccess     = "success"
	AgentStatusRepaired    = "repaired"
	AgentStatusFallback    = "fallback"
	AgentStatusMockSuccess = "mock_success"
	AgentStatusError       = "error"
)

// Fallback reason constants.
const (
	FallbackReasonNone             = "none"
	FallbackReasonLLMDisabled      = "llm_disabled"
	FallbackReasonLLMError         = "llm_error"
	FallbackReasonLLMTimeout       = "llm_timeout"
	FallbackReasonJSONParseFailed  = "json_parse_failed"
	FallbackReasonJSONRepairFailed = "json_repair_failed"
	FallbackReasonSchemaInvalid    = "schema_invalid"
	FallbackReasonPipelineError    = "pipeline_error"
	FallbackReasonUnknown          = "unknown"
	// K15-P0: Deep-specific fallback reasons
	FallbackReasonLLMAPIKeyMissing    = "llm_api_key_missing"
	FallbackReasonLLMClientMissing    = "llm_client_missing"
	FallbackReasonDeepCascadeFailed   = "deep_cascade_failed"
	FallbackReasonQualityExhausted    = "quality_exhausted"
	FallbackReasonQualityCancelled    = "quality_cancelled"
)


// Error code constants.
const (
	ErrorCodeNone             = "none"
	ErrorCodeLLMDisabled      = "LLM_DISABLED"
	ErrorCodeLLMError         = "LLM_ERROR"
	ErrorCodeLLMTimeout       = "LLM_TIMEOUT"
	ErrorCodeJSONParseFailed  = "JSON_PARSE_FAILED"
	ErrorCodeJSONRepairFailed = "JSON_REPAIR_FAILED"
	ErrorCodeSchemaInvalid    = "SCHEMA_INVALID"
	ErrorCodePipelineError    = "PIPELINE_ERROR"
	ErrorCodeMockFallbackUsed = "MOCK_FALLBACK_USED"
	ErrorCodeValidationError  = "VALIDATION_ERROR"
	ErrorCodeInternalError    = "INTERNAL_ERROR"
	ErrorCodeUnknownError     = "UNKNOWN_ERROR"
	// K15-P0: Deep-specific error codes
	ErrorCodeLLMAPIKeyMissing  = "LLM_API_KEY_MISSING"
	ErrorCodeLLMClientMissing  = "LLM_CLIENT_MISSING"
	ErrorCodeDeepCascadeFailed = "DEEP_CASCADE_FAILED"
	ErrorCodeQualityExhausted  = "QUALITY_EXHAUSTED"
	ErrorCodeQualityCancelled  = "QUALITY_CANCELLED"
)

// NewAgentResponseMeta creates a new AgentResponseMeta with the given agent name
// and derives all other fields from the business result metadata.
func NewAgentResponseMeta(agentName string) AgentResponseMeta {
	return AgentResponseMeta{
		AgentName:      agentName,
		GeneratedBy:    GeneratedByMockAgent,
		AgentStatus:    AgentStatusMockSuccess,
		FallbackReason: FallbackReasonNone,
		ErrorCode:      ErrorCodeNone,
		RepairApplied:  false,
		SchemaValid:    true,
		RequestID:      "",
	}
}

// WithGeneratedBy sets the generated_by field and returns the meta.
func (m AgentResponseMeta) WithGeneratedBy(generatedBy string) AgentResponseMeta {
	m.GeneratedBy = generatedBy
	return m
}

// WithAgentStatus sets the agent_status field and returns the meta.
func (m AgentResponseMeta) WithAgentStatus(status string) AgentResponseMeta {
	m.AgentStatus = status
	return m
}

// WithFallback sets fallback fields and returns the meta.
func (m AgentResponseMeta) WithFallback(reason, errorCode string) AgentResponseMeta {
	m.AgentStatus = AgentStatusFallback
	m.FallbackReason = reason
	m.ErrorCode = errorCode
	m.GeneratedBy = GeneratedByMockAgent
	return m
}

// WithRepaired sets repair fields and returns the meta.
func (m AgentResponseMeta) WithRepaired() AgentResponseMeta {
	m.AgentStatus = AgentStatusRepaired
	m.RepairApplied = true
	m.GeneratedBy = GeneratedByLLMAgent
	return m
}

// WithDeepFallback sets Deep fallback fields and returns the meta.
func (m AgentResponseMeta) WithDeepFallback(reason, errorCode string) AgentResponseMeta {
	m.GeneratedBy = GeneratedByDeepFallbackAgent
	m.AgentStatus = AgentStatusFallback
	m.FallbackReason = reason
	m.ErrorCode = errorCode
	return m
}

// DeriveMetaFromResult derives AgentResponseMeta from existing result metadata fields.
// This is a helper for transitioning from result-embedded metadata to data.meta.
func DeriveMetaFromResult(agentName, generatedBy, agentStatus, fallbackReason, errorCode string, repairApplied bool) AgentResponseMeta {
	meta := NewAgentResponseMeta(agentName)

	// Set generated_by
	if generatedBy != "" {
		meta.GeneratedBy = generatedBy
	}

	// Normalize agent_status: "mock" → "mock_success"
	switch agentStatus {
	case "mock":
		meta.AgentStatus = AgentStatusMockSuccess
	case AgentStatusSuccess, AgentStatusRepaired, AgentStatusFallback, AgentStatusMockSuccess, AgentStatusError:
		meta.AgentStatus = agentStatus
	default:
		if agentStatus != "" {
			meta.AgentStatus = agentStatus
		}
	}

	// Set repair_applied
	meta.RepairApplied = repairApplied

	// Normalize fallback_reason: empty string → "none"
	if fallbackReason != "" {
		meta.FallbackReason = fallbackReason
	} else {
		meta.FallbackReason = FallbackReasonNone
	}

	// Normalize error_code: empty string → "none"
	if errorCode != "" {
		meta.ErrorCode = errorCode
	} else {
		meta.ErrorCode = ErrorCodeNone
	}

	return meta
}
